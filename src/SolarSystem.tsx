function randomGenerator(seed: number) {
  return () => {
    seed = (Math.imul(1664525, seed) + 1013904223) >>> 0
    return seed / 4294967296
  }
}

function Stars({ mobile }: { mobile: boolean }) {
  const data = useMemo(() => {
    const count = mobile ? 2500 : 6200
    const random = randomGenerator(62485)
    const points = new Float32Array(count * 3)
    const intensity = new Float32Array(count)
    for (let index = 0; index < count; index++) {
      const z = random() * 2 - 1
      const angle = random() * Math.PI * 2
      const distance = 52 + random() * 75
      const width = Math.sqrt(1 - z * z) * distance
      points.set([Math.cos(angle) * width, Math.sin(angle) * width, z * distance], index * 3)
      intensity[index] = random()
    }
    return { points, intensity, count }
  }, [mobile])

  const uniforms = useMemo(() => ({ time: { value: 0 } }), [])
  useFrame(({ frameloop }, delta) => { if (frameloop === 'always') uniforms.time.value += Math.min(.05, delta) })

  return <points frustumCulled={false}>
    <bufferGeometry key={data.count}>
      <bufferAttribute attach="attributes-position" args={[data.points, 3]} />
      <bufferAttribute attach="attributes-strength" args={[data.intensity, 1]} />
    </bufferGeometry>
    <shaderMaterial transparent depthWrite={false} uniforms={uniforms}
      vertexShader={`attribute float strength;varying float v;void main(){v=strength;gl_PointSize=1.25+pow(v,6.)*2.55;gl_Position=projectionMatrix*modelViewMatrix*vec4(position,1.);}`}
      fragmentShader={`varying float v;uniform float time;void main(){float d=length(gl_PointCoord-.5);float a=1.-smoothstep(.04,.5,d);gl_FragColor=vec4(mix(vec3(.56,.68,.86),vec3(1.,.97,.89),v),a*(.36+v*.64)*(.83+.17*sin(v*160.+time*.9)));}`} />
  </points>
}

function Nebula() {
  const texture = useMemo(() => {
    const width = 256
    const height = 128
    const data = new Uint8Array(width * height * 4)
    const random = randomGenerator(9127)
    const cells = Float32Array.from({ length: 64 * 64 }, random)
    const sample = (u: number, v: number) => {
      const x = Math.floor(u)
      const y = Math.floor(v)
      const blendX = THREE.MathUtils.smoothstep(u - x, 0, 1)
      const blendY = THREE.MathUtils.smoothstep(v - y, 0, 1)
      const row = y * 64 + x
      return THREE.MathUtils.lerp(
        THREE.MathUtils.lerp(cells[row], cells[row + 1], blendX),
        THREE.MathUtils.lerp(cells[row + 64], cells[row + 65], blendX),
        blendY,
      )
    }
    for (let row = 0; row < height; row++) {
      for (let column = 0; column < width; column++) {
        const u = column / (width - 1)
        const v = row / (height - 1)
        const field = .52 * sample(u * 7, v * 5)
          + .28 * sample(u * 15 + 12, v * 10 + 15)
          + .20 * sample(u * 27 + 30, v * 23 + 35)
        const x = (u - .5) * 2
        const y = (v - .5) * 2 - .21 * Math.sin(x * 3)
        const falloff = Math.max(0, 1 - x * x - y * y * 2.8)
        const offset = (row * width + column) * 4
        data[offset] = 255
        data[offset + 1] = 255
        data[offset + 2] = 255
        data[offset + 3] = Math.round(field * field * falloff ** 2 * 215)
      }
    }
    const map = new THREE.DataTexture(data, width, height)
    map.magFilter = THREE.LinearFilter
    map.minFilter = THREE.LinearFilter
    map.needsUpdate = true
    return map
  }, [])

  useEffect(() => () => texture.dispose(), [texture])

  return <group>
    <mesh position={[16, -9, -31]} rotation={[0, 0, -.33]} renderOrder={-2}>
      <planeGeometry args={[59, 31]} />
      <meshBasicMaterial color="#8163d2" map={texture} transparent opacity={.22} depthWrite={false} blending={THREE.AdditiveBlending} />
    </mesh>
    <mesh position={[-12, -7, -27]} rotation={[0, 0, .37]} renderOrder={-2}>
      <planeGeometry args={[49, 19]} />
      <meshBasicMaterial color="#4a81b2" map={texture} transparent opacity={.16} depthWrite={false} blending={THREE.AdditiveBlending} />
    </mesh>
  </group>
}

function Dust() {
  const group = useRef<THREE.Points>(null)
  const positions = useMemo(() => {
    const random = randomGenerator(42)
    return Float32Array.from({ length: 210 }, (_, index) => (random() - .5) * [42, 21, 30][index % 3])
  }, [])

  useFrame((state, delta) => {
    if (!group.current || state.frameloop !== 'always') return
    group.current.rotation.y += Math.min(delta, .05) * .017
    const material = group.current.material as THREE.PointsMaterial
    material.opacity = .12 + .22 * Math.pow(.5 + .5 * Math.sin(state.clock.elapsedTime * .18), 5)
  })

  return <points ref={group}>
    <bufferGeometry><bufferAttribute attach="attributes-position" args={[positions, 3]} /></bufferGeometry>
    <pointsMaterial color="#a98dff" size={.042} opacity={.18} transparent depthWrite={false} />
  </points>
}

