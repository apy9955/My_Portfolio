/**
 * Scroll-Driven Cinematic Camera
 * Smoothly interpolates 3D camera trajectory through all planetary waypoints based on page scroll.
 */
function CinematicCamera({
  focus,
  onPlanetChange,
}: {
  focus: string
  onPlanetChange: (index: number) => void
}) {
  const camera = useRef<THREE.PerspectiveCamera>(null)
  const pointer = useRef(new THREE.Vector2())
  const rawScroll = useRef(0)
  const smoothScroll = useRef(0)
  const lookAt = useRef(new THREE.Vector3(0, .75, 0))

  const { posA, posB, targetA, targetB, desiredPos, desiredTarget } = useMemo(() => ({
    posA: new THREE.Vector3(),
    posB: new THREE.Vector3(),
    targetA: new THREE.Vector3(),
    targetB: new THREE.Vector3(),
    desiredPos: new THREE.Vector3(),
    desiredTarget: new THREE.Vector3(),
  }), [])

  const invalidate = useThree(state => state.invalidate)

  useEffect(() => { invalidate() }, [focus, invalidate])

  useEffect(() => {
    const move = (event: PointerEvent) => {
      if (event.pointerType === 'touch') return
      pointer.current.set(event.clientX / innerWidth * 2 - 1, 1 - event.clientY / innerHeight * 2)
    }

    const updateScroll = () => {
      const scrollable = document.documentElement.scrollHeight - window.innerHeight
      rawScroll.current = scrollable > 0 ? Math.min(1, Math.max(0, window.scrollY / scrollable)) : 0
    }

    updateScroll()
    window.addEventListener('scroll', updateScroll, { passive: true })
    window.addEventListener('resize', updateScroll)

    const reset = () => pointer.current.set(0, 0)
    window.addEventListener('pointermove', move, { passive: true })
    document.documentElement.addEventListener('pointerleave', reset)
    window.addEventListener('blur', reset)

    return () => {
      window.removeEventListener('pointermove', move)
      document.documentElement.removeEventListener('pointerleave', reset)
      window.removeEventListener('blur', reset)
      window.removeEventListener('scroll', updateScroll)
      window.removeEventListener('resize', updateScroll)
    }
  }, [])

  useFrame(({ scene, frameloop }, delta) => {
    if (!camera.current) return
    const playing = frameloop === 'always'
    const dt = Math.min(delta, 0.05)

    // Smooth scroll interpolation (damped steadicam effect)
    smoothScroll.current = THREE.MathUtils.damp(smoothScroll.current, rawScroll.current, 4.2, dt)

    const isScrollJourney = focus === 'Scroll Journey' || focus === 'Overview'

    if (isScrollJourney) {
      const p = smoothScroll.current

      // Identify current planetary segment between anchor stages
      let stageIndex = 0
      for (let i = 0; i < STAGE_ANCHORS.length - 1; i++) {
        if (p >= STAGE_ANCHORS[i] && p <= STAGE_ANCHORS[i + 1]) {
          stageIndex = i
          break
        }
      }

      // Notify parent of closest planetary body
      let closestIdx = 0
      let minDist = 999
      for (let i = 0; i < STAGE_ANCHORS.length; i++) {
        const d = Math.abs(p - STAGE_ANCHORS[i])
        if (d < minDist) {
          minDist = d
          closestIdx = i
        }
      }
      onPlanetChange(closestIdx)

      const s0 = STAGE_ANCHORS[stageIndex]
      const s1 = STAGE_ANCHORS[stageIndex + 1]
      const localT = (p - s0) / Math.max(0.0001, s1 - s0)
      // Smooth Hermite interpolation (smoothstep)
      const ease = localT * localT * (3 - 2 * localT)

      const metaA = celestialBodies[stageIndex]
      const metaB = celestialBodies[stageIndex + 1]

      // Resolve Body A position & camera target
      if (stageIndex === 0) {
        targetA.set(0, 0.75, 0)
        posA.set(0, 13.2, 21.8)
      } else {
        const objA = scene.getObjectByName(metaA.name)
        if (objA) {
          objA.getWorldPosition(targetA)
          posA.copy(targetA).add(metaA.offset)
        } else {
          targetA.set(0, 0.75, 0)
          posA.set(0, 13.2, 21.8)
        }
      }

      // Resolve Body B position & camera target
      const objB = scene.getObjectByName(metaB.name)
      if (objB) {
        objB.getWorldPosition(targetB)
        posB.copy(targetB).add(metaB.offset)
      } else {
        targetB.set(0, 0.75, 0)
        posB.set(0, 13.2, 21.8)
      }

      // Interpolate targets and camera coordinates
      desiredTarget.lerpVectors(targetA, targetB, ease)
      desiredPos.lerpVectors(posA, posB, ease)

      // Add graceful orbital arc lift during interplanetary flight
      const arcLift = Math.sin(ease * Math.PI) * 1.6
      desiredPos.y += arcLift

      // Subtle mouse parallax
      desiredPos.x += pointer.current.x * 0.4
      desiredPos.y += pointer.current.y * 0.25
    } else {
      // Manual focus on specific planet selected from dropdown
      const selectedIndex = celestialBodies.findIndex(b => b.name === focus)
      if (selectedIndex >= 0) onPlanetChange(selectedIndex)

      const body = focus === 'Sun' ? scene.getObjectByName('Sun') : scene.getObjectByName(focus)
      if (body) {
        body.getWorldPosition(desiredTarget)
        const meta = celestialBodies.find(b => b.name === focus)
        const offset = meta?.offset ?? new THREE.Vector3(1.2, 0.8, 2.2)
        desiredPos.copy(desiredTarget).add(offset)
        desiredPos.x += pointer.current.x * 0.3
        desiredPos.y += pointer.current.y * 0.2
      } else {
        desiredTarget.set(0, 0.75, 0)
        desiredPos.set(0, 13.2, 21.8)
      }
    }

    const weight = playing ? 1 - Math.exp(-4.5 * dt) : 1
    camera.current.position.lerp(desiredPos, weight)
    lookAt.current.lerp(desiredTarget, weight)
    camera.current.lookAt(lookAt.current)
  }, 0)

  return (
    <PerspectiveCamera
      ref={camera}
      makeDefault
      position={[0, 13.2, 21.8]}
      rotation={[-.52, 0, 0]}
      fov={48}
      near={.1}
      far={180}
    />
  )
}

function System({
  mobile,
  focus,
  onPlanetChange,
}: {
  mobile: boolean
  focus: string
  onPlanetChange: (index: number) => void
}) {
  const { viewport } = useThree()
  const narrow = viewport.aspect < 1

  return <>
    <CinematicCamera focus={focus} onPlanetChange={onPlanetChange} />
    <color attach="background" args={['#010409']} />
    <Stars mobile={mobile} />
    <Nebula />
    <Dust />
    <ambientLight intensity={.35} />
    <group position={narrow ? [1.8, 2.75, -.8] : [viewport.aspect > 1.55 ? 5.2 : 3.6, .9, -.5]} scale={narrow ? .76 : 1}>
      <pointLight color="#ffdfac" intensity={19} />
      <SystemBodies mobile={mobile} />
    </group>
  </>
}

function SystemBodies({ mobile }: { mobile: boolean }) {
  const group = useRef<THREE.Group>(null)
  const syncLight = () => {
    if (!group.current) return
    const center = group.current.getWorldPosition(new THREE.Vector3())
    group.current.traverse((object) => {
      if (object instanceof THREE.Mesh && object.material instanceof THREE.ShaderMaterial) {
        object.material.uniforms.sun?.value.copy(center)
      }
    })
  }
  const { size } = useThree()
  useEffect(syncLight, [size.width, size.height])

  return <group ref={group}>
    <Orbits />
    <Sun mobile={mobile} />
    {planets.map(planet => <Planet key={planet.name} planet={planet} mobile={mobile} />)}
  </group>
}

class SceneBoundary extends Component<{ children: ReactNode }, { failed: boolean }> {
  state = { failed: false }
  static getDerivedStateFromError() { return { failed: true } }
  render() { return this.state.failed ? null : this.props.children }
}

