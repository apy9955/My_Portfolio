/**
 * Main SolarSystem Component
 * Integrates the continuous 3D background with the interactive scroll-driven cinematic journey.
 */
export default function SolarSystem({
  paused,
  focus,
  hidden = false,
}: {
  paused: boolean
  focus: string
  hidden?: boolean
}) {
  const [mode, setMode] = useState({ mobile: false, visible: true })
  const [activePlanetIndex, setActivePlanetIndex] = useState(0)

  useEffect(() => {
    const compact = matchMedia('(max-width: 760px), (pointer: coarse)')
    const update = () => setMode({ mobile: compact.matches, visible: !document.hidden })
    update()
    compact.addEventListener('change', update)
    document.addEventListener('visibilitychange', update)
    return () => {
      compact.removeEventListener('change', update)
      document.removeEventListener('visibilitychange', update)
    }
  }, [])

  const handleSelectStage = (stage: number) => {
    const targetAnchor = STAGE_ANCHORS[stage] ?? 0
    const scrollable = document.documentElement.scrollHeight - window.innerHeight
    if (scrollable > 0) {
      window.scrollTo({
        top: targetAnchor * scrollable,
        behavior: 'smooth',
      })
    }
  }

  return (
    <>
      <div
        className="space-canvas"
        aria-hidden="true"
        style={hidden ? { opacity: 0.08, pointerEvents: 'none' } : undefined}
      >
        <SceneBoundary>
          <Canvas
            aria-hidden="true"
            dpr={mode.mobile ? 1 : [1, 1.5]}
            frameloop={paused || hidden || !mode.visible ? 'demand' : 'always'}
            gl={{ alpha: false, antialias: !mode.mobile, powerPreference: 'low-power' }}
            fallback={null}
          >
            <System
              mobile={mode.mobile}
              focus={focus}
              onPlanetChange={setActivePlanetIndex}
            />
          </Canvas>
        </SceneBoundary>
      </div>

      {/* Interactive Planet Information Overlay (Hidden on dedicated full-screen pages like /universe) */}
      {!hidden && (
        <PlanetInfoOverlay
          activePlanetIndex={activePlanetIndex}
          onSelectStage={handleSelectStage}
        />
      )}
    </>
  )
}
