type PlanetSpec = typeof planets[number]

function Planet({ planet, mobile }: { planet: PlanetSpec; mobile: boolean }) {
  const group = useRef<THREE.Group>(null)
  const globe = useRef<THREE.Mesh>(null)
  const moon = useRef<THREE.Mesh>(null)
  const moonAngle = useRef(.74)
  const angle = useRef(planet.angle)
  const y = Math.sin(planet.angle) * planet.orbit
  const x = Math.cos(planet.angle) * planet.orbit
  const uniforms = useMemo(() => ({
    tint: { value: new THREE.Color(planet.tint) },
    kind: { value: planet.kind },
    sun: { value: new THREE.Vector3() },
  }), [planet])

  useFrame(({ frameloop }, delta) => {
    if (frameloop !== 'always') return
    const step = Math.min(delta, .05)
    angle.current += step * planet.speed * 1.45
    if (moon.current) {
      moonAngle.current += step * .72
      moon.current.position.set(.82 * Math.cos(moonAngle.current), .10 * Math.sin(moonAngle.current), .82 * Math.sin(moonAngle.current))
    }
    if (group.current) group.current.position.set(Math.cos(angle.current) * planet.orbit, 0, Math.sin(angle.current) * planet.orbit)
    if (globe.current) globe.current.rotation.y += step * (planet.name === 'Venus' ? -.09 : .13)
  })

  return <group name={planet.name} ref={group} position={[x, 0, y]}>
    <mesh ref={globe} rotation={[.18, .6, -.29]}>
      <sphereGeometry args={[planet.radius, mobile ? 28 : 48, mobile ? 20 : 32]} />
      <shaderMaterial vertexShader={sphereVertex} fragmentShader={planetFragment} uniforms={uniforms} />
    </mesh>
    {planet.name === 'Earth' && <mesh ref={moon} name="Moon" position={[.60, .067, .55]}>
      <sphereGeometry args={[.1, 20, 14]} />
      <meshStandardMaterial color="#c5c6c7" roughness={1} />
    </mesh>}
    {planet.name === 'Saturn' && <mesh rotation={[-Math.PI / 2 + .24, .23, -.2]}>
      <ringGeometry args={[.83, 1.29, 96]} />
      <shaderMaterial vertexShader={ringVertex} fragmentShader={ringFragment} uniforms={uniforms} side={THREE.DoubleSide} transparent depthWrite={false} />
    </mesh>}
  </group>
}

